#!/usr/bin/env python3
"""Writes the configure-time headers SuperEmbedder's own CMake build would generate, for the UBT build of
the vendored library in SuperEmbedderCore (which runs no CMake), into
Source/SuperEmbedderCore/Private/Generated/.

Every value is derived from committed files, so the output is a pure function of the plugin tree:

  semb_engine_pin.h               superslm.lock's tag/commit/tree, engine_path_sha (the selected adapter
                                  TU's bytes), and SEMB_ENGINE_BUILD_RECORD
  superslm_build_record.inc       the SAME record, for engine_identity/build_identity.cpp (the engine
                                  identity verb this module compiles itself, under the rename)
  semb_certified_builds.h         docs/certified-builds.json and docs/certification-identity.json, byte for
                                  byte (the identity's bytes feed certification_epoch, so the fingerprint)
  semb_wq_population.h            the W-Q fixtures, verified against their manifest, as byte arrays (not raw
                                  string literals: the bytes then do not depend on the compiler's source
                                  character set)
  semb_witness_build_generation.h a 32-hex token; deterministic here (no witness executable is built)
  semb_compile_flags.h            "unrecorded", CMake's own placeholder value

The build record is one generator's output for both sides of the engine link check (the proposal's
section 3.1): the engine tag, the engine commit, "ubt-own-copy" and the plugin version, as
Source/ThirdParty/SuperSLM/VENDORED_VERSION.txt and SuperEmbedderUnreal.uplugin state them.

Usage:
  generate_semb_config.py [--plugin-root DIR]          write the headers
  generate_semb_config.py [--plugin-root DIR] --check  exit 1 naming each header that is not current
"""
from __future__ import annotations

import argparse
import hashlib
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent


def read_key_lines(path: Path, sep: str) -> dict[str, str]:
    out: dict[str, str] = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        if sep in line:
            k, _, v = line.partition(sep)
            out.setdefault(k.strip(), v.strip())
    return out


def byte_array(data: bytes) -> str:
    rows = []
    for i in range(0, len(data), 16):
        rows.append("    " + "".join(f"0x{b:02x}," for b in data[i:i + 16]))
    return "\n".join(rows) if rows else "    0x00,"


def char_array(data: bytes) -> str:
    """A char initializer of hex escapes: the bytes do not depend on the source or execution charset."""
    rows = []
    for i in range(0, len(data), 16):
        rows.append("    " + "".join(f"'\\x{b:02x}'," for b in data[i:i + 16]))
    return "\n".join(rows)


def build_record(root: Path) -> tuple[str, dict[str, str]]:
    tp = root / "Source" / "ThirdParty"
    engine = read_key_lines(tp / "SuperSLM" / "VENDORED_VERSION.txt", ":")
    lock = read_key_lines(tp / "SuperEmbedder" / "superslm.lock", "=")
    if engine.get("Tag") != lock.get("tag") or engine.get("Commit") != lock.get("commit"):
        raise SystemExit(f"SEMB_UE_ENGINE_PIN_MISMATCH: ThirdParty/SuperSLM is {engine.get('Tag')} @ "
                         f"{engine.get('Commit')}, but the vendored SuperEmbedder pins {lock.get('tag')} @ "
                         f"{lock.get('commit')}")
    uplugin = (root / "SuperEmbedderUnreal.uplugin").read_text(encoding="utf-8")
    m = re.search(r'"VersionName"\s*:\s*"([^"]*)"', uplugin)
    if not m:
        raise SystemExit("SEMB_UE_PLUGIN_VERSION_UNREADABLE: no VersionName in SuperEmbedderUnreal.uplugin")
    record = f"ubt-own-copy;engine={lock['tag']};engine_commit={lock['commit']};plugin={m.group(1)}"
    return record, lock


def render(root: Path) -> dict[str, str]:
    se = root / "Source" / "ThirdParty" / "SuperEmbedder"
    record, lock = build_record(root)
    banner = ("// Generated by ci/generate_semb_config.py from the vendored trees and the .uplugin. Do not edit;\n"
              "// re-run the generator (ci/host runs it with --check).\n")
    out: dict[str, str] = {}

    path_sha = hashlib.sha256((se / "src/superembedder/engine_adapter_interim.cpp").read_bytes()).hexdigest()
    out["semb_engine_pin.h"] = (
        banner + "#pragma once\n\n"
        f'#define SEMB_ENGINE_PIN_TAG "{lock["tag"]}"\n'
        f'#define SEMB_ENGINE_PIN_COMMIT "{lock["commit"]}"\n'
        f'#define SEMB_ENGINE_PIN_TREE_SHA "{lock["tree"]}"\n'
        f'#define SEMB_ENGINE_PATH_SHA "{path_sha}"\n'
        "// The pin tool's probe fills these in a CMake build. UBT has no probe: the toolchain the link check\n"
        "// compares is read from predefined macros on both sides of the same compile, and this build is\n"
        "// uncertified (SEMB_BUILD_SYSTEM \"ubt\" matches no certified cell).\n"
        '#define SEMB_ENGINE_TOOLCHAIN "unrecorded"\n'
        '#define SEMB_ENGINE_STDLIB "unrecorded"\n'
        '#define SEMB_ENGINE_DISPATCH "auto"\n'
        '#define SEMB_ENGINE_FLAGS_SHA "unrecorded"\n'
        f'#define SEMB_ENGINE_BUILD_RECORD "{record}"\n')
    out["superslm_build_record.inc"] = banner + f'#define SUPERSLM_BUILD_RECORD "{record}"\n'

    cb = (se / "docs/certified-builds.json").read_bytes()
    ci = (se / "docs/certification-identity.json").read_bytes()
    for name, data in (("certified-builds.json", cb), ("certification-identity.json", ci)):
        json.loads(data)  # refuse a file that is not JSON, as CMake's configure does
    out["semb_certified_builds.h"] = (
        banner + "#pragma once\n\n#include <cstddef>\n#include <cstdint>\n\nnamespace semb {\n\n"
        f"inline constexpr uint8_t kCertifiedBuildsDocument[] = {{\n{byte_array(cb)}\n}};\n"
        f"inline constexpr size_t kCertifiedBuildsDocumentSize = {len(cb)};\n"
        "static_assert(sizeof(kCertifiedBuildsDocument) == kCertifiedBuildsDocumentSize,\n"
        '              "the compiled-in certified-builds list must be the configured file\'s exact bytes");\n\n'
        f"inline constexpr uint8_t kCertificationIdentity[] = {{\n{byte_array(ci)}\n}};\n"
        f"inline constexpr size_t kCertificationIdentitySize = {len(ci)};\n"
        "static_assert(sizeof(kCertificationIdentity) == kCertificationIdentitySize,\n"
        '              "the compiled-in certification identity must be the configured file\'s exact bytes");\n\n'
        "}  // namespace semb\n")

    wq = se / "tests/fixtures/wq"
    manifest = json.loads((wq / "wq-queries.manifest.json").read_text(encoding="utf-8"))
    cap = manifest["truncation_content_cap"]
    if not (isinstance(cap, int) and cap > 0):
        raise SystemExit("SEMB_UE_WQ_MANIFEST: truncation_content_cap must be a positive integer")
    parts = []
    for fname, var in (("wq-queries.jsonl", "kWqJoinJsonl"), ("wq-truncation-leg.jsonl", "kWqTruncationJsonl")):
        data = (wq / fname).read_bytes()
        want = manifest["files"][fname]["sha256"]
        if hashlib.sha256(data).hexdigest() != want:
            raise SystemExit(f"SEMB_UE_WQ_FIXTURE_SHA_MISMATCH: {fname} does not match its manifest ({want})")
        # CMake writes the file into a raw string literal, and the compiler's first translation phase turns
        # each CR LF in source text into one new-line, so the library compiles the bytes with every CR LF
        # read as LF (wq-truncation-leg.jsonl ends in CR LF: 4,200 bytes on disk, 4,199 compiled). The
        # byte array reproduces what the CMake build compiles, not the file.
        data = data.replace(b"\r\n", b"\n")
        if b"\r" in data:
            raise SystemExit(f"SEMB_UE_WQ_FIXTURE_LONE_CR: {fname} carries a CR outside CR LF; its compiled bytes "
                             "would depend on the compiler")
        parts.append(f"inline constexpr char {var}Bytes_[] = {{\n{char_array(data)}\n}};\n"
                     f"inline constexpr std::string_view {var}{{{var}Bytes_, {len(data)}}};\n")
    out["semb_wq_population.h"] = (
        banner + "#pragma once\n\n#include <cstddef>\n#include <string_view>\n\nnamespace semb {\n\n"
        + "\n".join(parts) + f"inline constexpr size_t kWqTruncationContentCap = {cap};\n\n}}  // namespace semb\n")

    token = hashlib.sha256(("ubt-own-copy-witness:" + record).encode()).hexdigest()[:32]
    out["semb_witness_build_generation.h"] = (
        banner + "#pragma once\n\n"
        f'#define SEMB_WITNESS_BUILD_GENERATION_TOKEN "{token}"\n'
        "static_assert(sizeof(SEMB_WITNESS_BUILD_GENERATION_TOKEN) == 33,\n"
        '              "SEMB_WITNESS_BUILD_GENERATION_TOKEN must be a 32-hex-character string literal");\n')
    out["semb_compile_flags.h"] = banner + '#pragma once\n#define SEMB_COMPILE_FLAGS_SHA "unrecorded"\n'
    return out


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--plugin-root", type=Path, default=HERE.parent)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    root = a.plugin_root.resolve()
    gen = root / "Source" / "SuperEmbedderCore" / "Private" / "Generated"
    stale = []
    for name, text in render(root).items():
        path = gen / name
        if a.check:
            if not path.is_file() or path.read_bytes() != text.encode("utf-8"):
                stale.append(name)
        else:
            gen.mkdir(parents=True, exist_ok=True)
            path.write_bytes(text.encode("utf-8"))
    if stale:
        print("SEMB_UE_GENERATED_STALE: " + ", ".join(stale) + " (re-run ci/generate_semb_config.py)")
        return 1
    print(("current: " if a.check else "wrote: ") + str(gen))
    return 0


if __name__ == "__main__":
    sys.exit(main())
